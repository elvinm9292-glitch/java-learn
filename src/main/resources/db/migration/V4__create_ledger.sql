-- Journal of money movements: one operation, one entry per touched account.
-- Entries of one operation always sum to zero (checked in Operation, not in the database).

CREATE TABLE java_learn.operation (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    type       VARCHAR(20) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT pk_operation PRIMARY KEY (id),
    CONSTRAINT chk_operation_type CHECK (type IN ('TRANSFER'))
);

CREATE TABLE java_learn.ledger_entry (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    operation_id BIGINT NOT NULL,
    account_id   BIGINT NOT NULL,
    amount       NUMERIC(19, 2) NOT NULL,
    CONSTRAINT pk_ledger_entry PRIMARY KEY (id),
    CONSTRAINT fk_ledger_entry_operation FOREIGN KEY (operation_id) REFERENCES java_learn.operation (id),
    CONSTRAINT fk_ledger_entry_account FOREIGN KEY (account_id) REFERENCES java_learn.account (id),
    CONSTRAINT chk_ledger_entry_amount_not_zero CHECK (amount <> 0)
);

-- PostgreSQL does not index foreign keys by itself; statements are read by account
CREATE INDEX idx_ledger_entry_account ON java_learn.ledger_entry (account_id);
CREATE INDEX idx_ledger_entry_operation ON java_learn.ledger_entry (operation_id);
